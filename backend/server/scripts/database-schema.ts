import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateDrizzleJson, generateMigration } from 'drizzle-kit/api';
import { applicationSchema } from '../src/platform/database/schema';

export const databaseSchemaSqlPath = fileURLToPath(new URL('../src/platform/database/current.sql', import.meta.url));

/** Empty → current schema only. There is no version chain or legacy adapter. */
export async function generateDatabaseSchemaSql(): Promise<string> {
  const empty = generateDrizzleJson({});
  const current = generateDrizzleJson(applicationSchema, undefined, ['resources', 'auth', 'catalog']);
  const statements = await generateMigration(empty, current);
  return [
    '-- Generated by backend/server/scripts/database-schema.ts from Drizzle schema. Do not edit.',
    '-- Current initialization only; resource RLS is installed by D02.',
    'CREATE EXTENSION IF NOT EXISTS ltree;',
    'CREATE EXTENSION IF NOT EXISTS vector;',
    'CREATE EXTENSION IF NOT EXISTS pg_search;',
    ...statements,
    '',
  ].join('\n');
}

async function main() {
  const sql = await generateDatabaseSchemaSql();
  const command = process.argv[2] ?? '--check';
  if (command === '--write') {
    await writeFile(databaseSchemaSqlPath, sql, 'utf8');
    console.log(`Generated current schema: ${databaseSchemaSqlPath}`);
  } else if (command === '--sql') {
    process.stdout.write(sql);
  } else if (command === '--check') {
    const saved = await readFile(databaseSchemaSqlPath, 'utf8');
    if (saved.replaceAll('\r\n', '\n') !== sql) throw new Error('Current SQL has drifted. Run bun backend/server/scripts/database-schema.ts --write.');
    console.log('Fob current SQL matches the Drizzle source.');
  } else {
    throw new Error('Usage: bun backend/server/scripts/database-schema.ts [--check|--write|--sql]');
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
