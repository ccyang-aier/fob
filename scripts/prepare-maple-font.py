"""Prepare the pinned, self-hosted Maple Mono code font using only Python's standard library."""
from hashlib import sha256
from pathlib import Path
from urllib.request import urlretrieve
import re
import tarfile

ROOT = Path(__file__).resolve().parent.parent
ARCHIVE = ROOT / ".runtime" / "font-sources" / "maple-mono-5.3.0.tgz"
SOURCE = "https://registry.npmjs.org/@fontsource/maple-mono/-/maple-mono-5.3.0.tgz"
DIGEST = "5d21b3a697334a11be74eddfd2dcc5092964deec4642041ac956df87a3e7fc79"
OUTPUT = ROOT / "public" / "fonts" / "code" / "maple-mono"
# Fontsource 5.3.0 swaps the Medium and SemiBold source filenames.
# Register each face under its actual upstream name and weight.
FACES = [("400", 400, "Regular"), ("600", 500, "Medium"), ("500", 600, "SemiBold"), ("700", 700, "Bold"), ("400-italic", 400, "Italic")]


def prepare():
    ARCHIVE.parent.mkdir(parents=True, exist_ok=True)
    if not ARCHIVE.exists():
        urlretrieve(SOURCE, ARCHIVE)
    if sha256(ARCHIVE.read_bytes()).hexdigest() != DIGEST:
        raise ValueError("Maple Mono archive does not match the pinned checksum")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    css_parts = ["/* Generated by scripts/prepare-maple-font.py. Maple Mono v7.8, SIL OFL 1.1. */"]
    with tarfile.open(ARCHIVE) as archive:
        for style, weight, name in FACES:
            css = archive.extractfile(f"package/{style}.css").read().decode("utf-8")
            filename = re.search(r"\./files/([^)]*\.woff2)", css).group(1)
            asset = f"MapleMono-{name}.woff2"
            (OUTPUT / asset).write_bytes(archive.extractfile(f"package/files/{filename}").read())
            css = re.sub(r"/\*[^*]*\*/", f"/* Maple Mono {name} */", css, count=1)
            css = re.sub(r"font-weight: \d+;", f"font-weight: {weight};", css)
            css_parts.append(re.sub(r"src: [^;]+;", f'src: url("/fonts/code/maple-mono/{asset}") format("woff2");', css))
        (OUTPUT / "OFL.txt").write_bytes(archive.extractfile("package/LICENSE").read())
    (ROOT / "src" / "app" / "code-fonts.css").write_text("\n".join(css_parts), encoding="utf-8")
    (OUTPUT / "SOURCE.txt").write_text(
        f"Maple Mono v7.8\nUpstream: https://github.com/subframe7536/maple-font\n"
        f"Fontsource package: @fontsource/maple-mono 5.3.0\nSource: {SOURCE}\n"
        f"SHA256: {DIGEST}\nLicense: SIL OFL 1.1\n", encoding="utf-8",
    )
    print(f"Prepared {len(FACES)} Maple Mono faces")


if __name__ == "__main__":
    prepare()
