"""Prepare self-hosted document fonts. Requires fonttools==4.66.1 and brotli==1.2.0."""
from pathlib import Path
from urllib.request import urlretrieve
from fontTools.ttLib import TTFont
from fontTools import subset
import logging
import re
import tarfile
import sys

logging.getLogger("fontTools.subset").setLevel(logging.ERROR)
ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / ".runtime" / "font-sources"
OUTPUT = ROOT / "public" / "fonts" / "document"
STYLESHEET = ROOT / "src" / "features" / "knowledge" / "editor" / "document-fonts.css"
FONTS = [
    ("wenkai", "Fob Document WenKai", "lxgw/LxgwWenKai", "v1.522", "LXGWWenKai-Regular.ttf"),
    ("wenkai-screen", "Fob Document WenKai Screen", "lxgw/LxgwWenKai-Screen", "v1.522", "LXGWWenKaiScreen.ttf"),
    ("zhenkai", "Fob Document ZhenKai", "lxgw/LxgwZhenKai", "v0.825", "LXGWZhenKaiGB-Regular.ttf"),
]

def prepare():
    CACHE.mkdir(parents=True, exist_ok=True)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    css = ["/* Generated by scripts/prepare-document-fonts.py. OFL licenses accompany assets. */"]
    for slug, family, repository, version, filename in FONTS:
        source = CACHE / filename
        url = f"https://github.com/{repository}/releases/download/{version}/{filename}"
        if not source.exists():
            urlretrieve(url, source)
        directory = OUTPUT / slug
        directory.mkdir(exist_ok=True)
        urlretrieve(f"https://raw.githubusercontent.com/{repository}/main/OFL.txt", directory / "OFL.txt")
        license_path = directory / "OFL.txt"
        license_path.write_text("\n".join(line.rstrip() for line in license_path.read_text(encoding="utf-8").splitlines()) + "\n", encoding="utf-8")
        (directory / "SOURCE.txt").write_text(f"Source: {url}\nLicense: SIL OFL 1.1\nUnicode subsets, WOFF2 compression and renamed font families; original glyph outlines retained.\n", encoding="utf-8")
        with TTFont(source) as original:
            codepoints = sorted(original.getBestCmap())
        # Disjoint ranges let browsers fetch only the characters actually rendered.
        for block in sorted({codepoint // 1024 for codepoint in codepoints}):
            start, end = block * 1024, block * 1024 + 1023
            with TTFont(source) as font:
                options = subset.Options()
                options.layout_features = ["*"]
                subsetter = subset.Subsetter(options=options)
                subsetter.populate(unicodes=[point for point in codepoints if start <= point <= end])
                subsetter.subset(font)
                for record in font["name"].names:
                    if record.nameID in (1, 4, 6, 16):
                        record.string = (family.replace(" ", "") if record.nameID == 6 else family).encode(record.getEncoding())
                font.flavor = "woff2"
                asset = f"{start:05x}.woff2"
                font.save(directory / asset)
            css.append(f'@font-face {{ font-family: "{family}"; font-style: normal; font-weight: 400; font-display: swap; src: url("/fonts/document/{slug}/{asset}") format("woff2"); unicode-range: U+{start:X}-{end:X}; }}')
        print(f"Prepared {slug}", flush=True)
    STYLESHEET.write_text("\n".join(css) + "\n", encoding="utf-8")

def prepare_serif():
    archive_path = CACHE / "noto-serif-sc.tgz"
    url = "https://registry.npmjs.org/@fontsource/noto-serif-sc/-/noto-serif-sc-5.3.0.tgz"
    if not archive_path.exists():
        urlretrieve(url, archive_path)
    directory = OUTPUT / "noto-serif"
    directory.mkdir(parents=True, exist_ok=True)
    with tarfile.open(archive_path) as archive:
        css = archive.extractfile("package/400.css").read().decode("utf-8")
        for filename in re.findall(r"\./files/([^)]*\.woff2)", css):
            (directory / filename).write_bytes(archive.extractfile(f"package/files/{filename}").read())
        (directory / "OFL.txt").write_bytes(archive.extractfile("package/LICENSE").read())
    css = re.sub(r"src: url\(\./files/([^)]*\.woff2)\)[^;]*;", r'src: url("/fonts/document/noto-serif/\1") format("woff2");', css)
    with STYLESHEET.open("a", encoding="utf-8") as stylesheet:
        stylesheet.write(css)
    (directory / "SOURCE.txt").write_text(f"Noto Serif SC (the Noto distribution of Source Han Serif)\nUpstream: https://github.com/notofonts/noto-cjk\nWeb subsets: {url}\nLicense: SIL OFL 1.1\n", encoding="utf-8")

def prepare_code_fonts():
    css_parts = ["/* Generated by scripts/prepare-document-fonts.py --code-only. SIL OFL 1.1. */"]
    for slug, upstream in [("jetbrains-mono", "JetBrains/JetBrainsMono"), ("fira-code", "tonsky/FiraCode"), ("source-code-pro", "adobe-fonts/source-code-pro"), ("ibm-plex-mono", "IBM/plex")]:
        archive_path = CACHE / f"{slug}-5.3.0.tgz"
        url = f"https://registry.npmjs.org/@fontsource/{slug}/-/{slug}-5.3.0.tgz"
        CACHE.mkdir(parents=True, exist_ok=True)
        if not archive_path.exists():
            urlretrieve(url, archive_path)
        directory = OUTPUT / slug
        directory.mkdir(parents=True, exist_ok=True)
        with tarfile.open(archive_path) as archive:
            css = archive.extractfile("package/400.css").read().decode("utf-8")
            for filename in re.findall(r"\./files/([^)]*\.woff2)", css):
                (directory / filename).write_bytes(archive.extractfile(f"package/files/{filename}").read())
            (directory / "OFL.txt").write_bytes(archive.extractfile("package/LICENSE").read())
        css = re.sub(r"src: url\(\./files/([^)]*\.woff2)\)[^;]*;", rf'src: url("/fonts/document/{slug}/\1") format("woff2");', css)
        css_parts.append(css)
        (directory / "SOURCE.txt").write_text(f"Upstream: https://github.com/{upstream}\nWeb subsets: {url}\nLicense: SIL OFL 1.1\n", encoding="utf-8")
    STYLESHEET.with_name("code-fonts.css").write_text("\n".join(css_parts), encoding="utf-8")

if __name__ == "__main__":
    if "--code-only" not in sys.argv:
        prepare()
        prepare_serif()
    prepare_code_fonts()
